 
%оформление графика с помощью дескрипторной графики
%дескрипторная графика имеет дело с базовыми графическими объектами
%дескрипторная графика это низкоуровневая графика системы MATLAB 
%оформление осей координат


clc   %clears all  from the Command Window
clear %removes all variables from the workspace (memory) 

x = 0:0.1:3;  y = sin(x);

%функция plot рсует линию с параметрами по умолчанию
plot(x,y);
pause

%функция exis устанавливает пределы по оси 'x' и 'y' 
axis([1.5, 2.5, 0.5, 2 ]);
pause

%функция gca возвращает дескриптор текущих осей координат (гарафический объект axis)  
hAxes = gca;
%функция set устанавливает метки вдоль оси 'x' координатных осей hAxes
set(hAxes,'xtick',[1.5 1.75 2.0 2.25 2.5])
pause

%устанавливаем метку на оси 'x' текущих осей координат
xlabel('x coordinate')
%устанавливаем метку на оси 'y' текущих осей координат
ylabel('sin(x)')
pause

%функция text рисует текстовые символы в данной позиции
%стилем заданным по умолчанию и еще !!!
%функция text возвращает дескриптор hText графического объекта text
hText = text(2.1, 0.9, '\leftarrowsin(x)');
pause

%функция set устанавливает новые атрибуты объекта text
set(hText,'Color',[0 1 0],'FontSize',[18]);
pause

%функция set устанавливает новый  цвет фона объекта axis
set(hAxes,'Color',[0.5 0.8 0.5]);
pause

%функция gcf возвращает дескриптор текущего окна (графический объект figure)  
hFigure = gcf;
%функция set устанавливает новый  цвет фона объекта figure
set(hFigure,'Color',[0.8 0.5 0.5]);
pause


%функция text рисует текстовые символы в данной позиции
%стилем заданным по умолчанию и еще !!!
%функция text возвращает дескриптор hText1 графического объекта text
hText1 = text(2.0, 1.5,'Very good\newlinetext')
pause
%функция set устанавливает новые атрибуты объекта text1
set(hText1,'Color',[1.0 0.5 0.0],'FontSize',[24]);
pause


%функция line рисует линию по заданным точкам
%стилем заданным по умолчанию и еще !!!
%функция line возвращает дескриптор hLine графического объекта line
hLine = line([1.8,2.4,2.4,1.8,1.8],[1.2,1.2,1.8,1.8,1.2]);
pause
%функция set устанавливает новые атрибуты объекта line
set(hLine,'Color',[0.0 1.0 1.0],'LineWidth', 7);










